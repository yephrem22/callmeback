"""Generate the app's own secrets into .env (PLAN.md §0.4 "App secrets", §7.1, §23.1).

Writes INTERNAL_TOKEN, MCP_TOKEN, DASH_USER and a Caddy-compatible bcrypt
DASH_PASS_HASH ($2a$, single-quoted so its "$" signs survive). Values that are
already valid are never touched; placeholders are replaced in place; missing
keys are appended. The dashboard password is printed once and never stored.
Contract: specs/001-env-readiness/contracts/gen-secrets-cli.md.
"""
from __future__ import annotations

import argparse
import os
import re
import secrets
import sys
import tempfile
from pathlib import Path

from scripts.check_env import BCRYPT_RE, MIN_TOKEN_LEN, REPO_ROOT, is_placeholder

GENERATED_HEADER = "# --- generated by make secrets (spec 001)"
LINE_RE = re.compile(r"^(?P<key>[A-Za-z_][A-Za-z0-9_]*)=(?P<value>.*?)(?P<comment>\s+#.*)?$")
ORDER = ("INTERNAL_TOKEN", "MCP_TOKEN", "DASH_USER", "DASH_PASS_HASH")


def _unquote(raw: str) -> str:
    v = raw.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        return v[1:-1]
    return v


def is_valid(key: str, value: str) -> bool:
    if key in ("INTERNAL_TOKEN", "MCP_TOKEN"):
        return not is_placeholder(value) and len(value) >= MIN_TOKEN_LEN
    if key == "DASH_USER":
        return bool(value.strip())
    if key == "DASH_PASS_HASH":
        return not is_placeholder(value) and BCRYPT_RE.match(value) is not None
    return False


def new_values(rounds: int) -> tuple[dict[str, str], str]:
    """Fresh values for every key, and the plain dashboard password."""
    import bcrypt
    password = secrets.token_urlsafe(12)
    hashed = bcrypt.hashpw(password.encode(), bcrypt.gensalt(rounds=rounds, prefix=b"2a")).decode()
    return {
        "INTERNAL_TOKEN": secrets.token_urlsafe(32),
        "MCP_TOKEN": secrets.token_urlsafe(32),
        "DASH_USER": "demo",
        "DASH_PASS_HASH": f"'{hashed}'",
    }, password


def plan_changes(lines: list[str]) -> dict[str, tuple[str, int | None]]:
    """For each key: ("kept" | "replaced placeholder" | "written", line index or None)."""
    found: dict[str, tuple[str, int]] = {}
    for i, line in enumerate(lines):
        m = LINE_RE.match(line.rstrip("\n"))
        if m and m.group("key") in ORDER and m.group("key") not in found:
            found[m.group("key")] = (_unquote(m.group("value")), i)
    plan: dict[str, tuple[str, int | None]] = {}
    for key in ORDER:
        if key in found:
            value, idx = found[key]
            plan[key] = ("kept", idx) if is_valid(key, value) else ("replaced placeholder", idx)
        else:
            plan[key] = ("written", None)
    return plan


def apply(lines: list[str], plan: dict, values: dict[str, str]) -> list[str]:
    out = list(lines)
    appended: list[str] = []
    for key in ORDER:
        action, idx = plan[key]
        if action == "kept":
            continue
        if action == "replaced placeholder":
            m = LINE_RE.match(out[idx].rstrip("\n"))
            comment = m.group("comment") or ""
            out[idx] = f"{key}={values[key]}{comment}\n"
        else:
            appended.append(f"{key}={values[key]}\n")
    if appended:
        if out and not out[-1].endswith("\n"):
            out[-1] += "\n"
        if out and out[-1].strip():
            out.append("\n")
        out.append(GENERATED_HEADER + "\n")
        out.extend(appended)
    return out


def write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".env.", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(content)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate app secrets into .env (PLAN.md §0.4)")
    parser.add_argument("--env-file", default=str(REPO_ROOT / ".env"))
    parser.add_argument("--rounds", type=int, default=14, help="bcrypt cost (default 14, like caddy hash-password)")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)
    path = Path(args.env_file)

    lines = path.read_text().splitlines(keepends=True) if path.is_file() else []
    plan = plan_changes(lines)
    if all(action == "kept" for action, _ in plan.values()):
        print("Nothing to do; all app secrets present.")
        return 0

    values, password = new_values(args.rounds)
    try:
        write_atomic(path, "".join(apply(lines, plan, values)))
    except OSError as exc:
        print(f"could not write {path}: {exc}", file=sys.stderr)
        return 1

    if plan["DASH_PASS_HASH"][0] == "kept":
        print("Dashboard hash kept; the password is unchanged.")
    else:
        user = values["DASH_USER"] if plan["DASH_USER"][0] != "kept" else "<your DASH_USER>"
        print(f"Dashboard login: user {user}, password {password}")
        print("Save it now; only the hash is stored.")
    if not args.quiet:
        for key in ORDER:
            print(f"{key}: {plan[key][0]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
